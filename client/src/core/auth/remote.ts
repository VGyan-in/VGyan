import { ApiError, AUTH_TOKEN_KEY, patchJson, postJson } from "@/core/api/client";
import { isServerConfigured } from "@/core/config";
import type { Repository } from "@/core/db/types";
import { secureStore } from "@/core/storage/secure";
import type { StudentProfile } from "@/types/models";

/** Why a server auth call failed, in the terms the sign-in screens show. */
export type RemoteAuthError =
  | "not-found"
  | "wrong-password"
  | "participant-exists"
  | "email-exists"
  | "invalid-class-code"
  | "registration-closed"
  | "network"
  | "server";

export type RemoteAuthResult = { ok: true; participantId: string } | { ok: false; error: RemoteAuthError };

interface TokenResponse {
  access_token?: unknown;
  participant_id?: unknown;
}

/**
 * `POST /student/register`. When the participant ID was generated by the app (not typed by a
 * teacher), a collision is retried with a fresh ID so registration never fails on chance.
 */
export async function remoteRegister(input: {
  participantId: string;
  generated: boolean;
  regenerate: () => string;
  fullName: string;
  email: string;
  password: string;
  classCode?: string;
}): Promise<RemoteAuthResult> {
  let pid = input.participantId;
  for (let attempt = 0; attempt < 4; attempt++) {
    try {
      const res = await postJson<TokenResponse>("/student/register", {
        student_id: pid,
        fullName: input.fullName,
        email: input.email || undefined,
        password: input.password,
        classCode: input.classCode || undefined,
      });
      if (typeof res.access_token !== "string") return { ok: false, error: "server" };
      await secureStore.set(AUTH_TOKEN_KEY, res.access_token);
      return { ok: true, participantId: typeof res.participant_id === "string" ? res.participant_id : pid };
    } catch (e) {
      if (e instanceof ApiError && e.code === "participant_exists" && input.generated) {
        pid = input.regenerate();
        continue;
      }
      return { ok: false, error: registerError(e) };
    }
  }
  return { ok: false, error: "participant-exists" };
}

/** `POST /student/login` → `{ access_token }`, stored in secure storage for the API client and uploader. */
export async function remoteLogin(identifier: string, password: string): Promise<RemoteAuthResult> {
  try {
    const res = await postJson<TokenResponse>("/student/login", { student_id: identifier, password });
    if (typeof res.access_token !== "string" || res.access_token === "") return { ok: false, error: "server" };
    await secureStore.set(AUTH_TOKEN_KEY, res.access_token);
    return { ok: true, participantId: typeof res.participant_id === "string" ? res.participant_id : identifier.toUpperCase() };
  } catch (e) {
    if (!(e instanceof ApiError) || e.status === null) return { ok: false, error: "network" };
    return { ok: false, error: ({ 401: "wrong-password", 404: "not-found" } as const)[e.status as 401 | 404] ?? "server" };
  }
}

export async function clearAuthToken() {
  await secureStore.remove(AUTH_TOKEN_KEY);
}

const PROFILE_KEYS = ["grade", "section", "school", "schoolType", "medium", "nativeLanguage", "otherLanguages", "ageGroup", "gender"] as const;

/**
 * Pushes the background-details profile (and a class join code, if entered) to `PATCH /student/me`.
 * A dirty flag in SQLite makes this survive offline edits and app restarts.
 */
export async function syncProfile(repo: Repository, profile: StudentProfile, classCode?: string): Promise<boolean> {
  const dirtyKey = `profile.dirty.${profile.participantId}`;
  const pendingCodeKey = `profile.classCode.${profile.participantId}`;
  if (classCode) await repo.setMeta(pendingCodeKey, classCode.trim().toUpperCase());
  const code = await repo.getMeta(pendingCodeKey);
  if (!isServerConfigured() || (!code && (await repo.getMeta(dirtyKey)) !== "1")) return false;
  if (!(await secureStore.get(AUTH_TOKEN_KEY))) return false;
  const body: Record<string, string> = { name: profile.name };
  for (const k of PROFILE_KEYS) body[k] = profile[k] ?? "";
  if (code) body.classCode = code;
  try {
    await patchJson("/student/me", body);
  } catch (e) {
    if (e instanceof ApiError && e.code === "invalid_class_code") {
      await repo.setMeta(pendingCodeKey, null);
      throw e;
    }
    return false;
  }
  await repo.setMeta(dirtyKey, null);
  await repo.setMeta(pendingCodeKey, null);
  return true;
}

function registerError(e: unknown): RemoteAuthError {
  if (!(e instanceof ApiError) || e.status === null) return "network";
  switch (e.code) {
    case "participant_exists":
      return "participant-exists";
    case "email_exists":
      return "email-exists";
    case "invalid_class_code":
      return "invalid-class-code";
    case "registration_closed":
      return "registration-closed";
    default:
      return "server";
  }
}
